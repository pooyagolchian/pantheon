#!/usr/bin/env bash
# capture.sh — snapshot this machine's Claude Code setup into the repo.
#
#   skills/manifest.tsv   every installed skill: profile, source, name
#                         (source = a skills.sh / GitHub repo, or "vendor")
#   skills/vendor/<name>  copies of skills with no known upstream source
#   plugins.tsv           plugin marketplaces and user-scope plugins
#   core/settings.json    skillOverrides from settings.json
#
# A skill's source is looked up in: ~/.agents/.skill-lock.json (global skills.sh lock),
# every skills-lock.json under $HOME (project locks), then skills/known-sources.tsv.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CLAUDE_DIR="${CLAUDE_DIR:-$HOME/.claude}"
AGENTS_DIR="${AGENTS_DIR:-$HOME/.agents}"
INCLUDE_OFF="${INCLUDE_OFF:-0}"   # 1 = also capture skills switched off in skillOverrides
DRY_RUN="${DRY_RUN:-0}"

command -v jq >/dev/null || { echo "jq is required" >&2; exit 1; }

tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
sources="$tmp/sources.tsv"   # skill \t source, first match wins

# 0. skills pinned to "vendor" (upstream removed them), 1. global lock, 2. project locks,
# 3. hand-maintained known sources
{
  awk -F'\t' '!/^#/ && $2=="vendor"' "$ROOT/skills/known-sources.tsv" 2>/dev/null || true
  [ -f "$AGENTS_DIR/.skill-lock.json" ] && jq -r '.skills | to_entries[] | "\(.key)\t\(.value.source)"' "$AGENTS_DIR/.skill-lock.json"
  { find "$HOME" -maxdepth 4 -name skills-lock.json -not -path '*/node_modules/*' -not -path "$ROOT/*" 2>/dev/null || true; } |
    while read -r f; do jq -r '.skills | to_entries[] | "\(.key)\t\(.value.source)"' "$f" 2>/dev/null || true; done
  grep -v '^#' "$ROOT/skills/known-sources.tsv" 2>/dev/null || true
} | awk -F'\t' 'NF==2 && !seen[$1]++' > "$sources"

# Profile for a skill, from its name and source. Edit freely; `make capture` re-applies it.
profile_for() {
  local name="$1" src="$2"
  case "$name" in
    find-skills|skill-creator|mcp-builder|claude-api|find-docs|webapp-testing|full-output-enforcement|deslop|template-skill) echo core; return ;;
    resume-*|cover-letter-*|job-description-*|application-form-filler|tailored-resume-*|rendercv) echo career; return ;;
    docx|pdf|pptx|xlsx|doc-coauthoring|internal-comms|slack-gif-creator) echo docs; return ;;
    microsoft-*|azure-*|aws-*|cloudflare-*) echo cloud; return ;;
    pooya-*) echo personal; return ;;
    seo*|*-seo|ai-seo|schema|programmatic-seo|site-architecture|product-hunt-launch) echo marketing; return ;;
    next*|react*|vercel*|turborepo|shadcn|tailwind*|core-web-vitals|performance|web-quality-audit|best-practices|accessibility*|*-accessibility|fixing-*|responsive-design|building-components|frontend-ui-engineering|improve-react|web-artifacts-builder) echo frontend; return ;;
  esac
  case "$src" in
    coreyhaines31/marketingskills) echo marketing; return ;;
  esac
  echo design
}

rows="$tmp/rows.tsv"; : > "$rows"
vendored=0; sourced=0; skipped=""
for path in "$CLAUDE_DIR"/skills/*; do
  name="$(basename "$path")"
  [ "$name" = synced ] && continue                       # claude.ai sync bucket — never touch
  [ -f "$path/SKILL.md" ] || continue
  target="$(readlink "$path" 2>/dev/null || true)"
  case "$target" in "$ROOT/plugins/"*) continue ;; esac  # Pantheon's own skills
  if [ "$INCLUDE_OFF" != 1 ] && [ "$(jq -r --arg n "$name" '.skillOverrides[$n] // ""' "$CLAUDE_DIR/settings.json" 2>/dev/null)" = off ]; then
    skipped="$skipped $name"; continue
  fi
  src="$(awk -F'\t' -v n="$name" '$1==n {print $2; exit}' "$sources")"
  case "$target" in "$ROOT/skills/vendor/"*) src="" ;; esac
  [ "$src" = vendor ] && src=""
  if [ -n "$src" ]; then
    printf '%s\t%s\t%s\n' "$(profile_for "$name" "$src")" "$src" "$name" >> "$rows"; sourced=$((sourced+1))
  else
    printf '%s\t%s\t%s\n' "$(profile_for "$name" vendor)" vendor "$name" >> "$rows"; vendored=$((vendored+1))
    case "$target" in "$ROOT/skills/vendor/"*) continue ;; esac  # already lives here
    if [ "$DRY_RUN" = 1 ]; then echo "  [dry] vendor $name"; else
      mkdir -p "$ROOT/skills/vendor/$name"
      rsync -aL --delete --exclude .git --exclude node_modules --exclude .DS_Store "$path/" "$ROOT/skills/vendor/$name/"
    fi
  fi
done

out() { if [ "$DRY_RUN" = 1 ]; then echo "  [dry] write ${1#"$ROOT"/}"; cat > /dev/null; else cat > "$1"; fi; }

{
  printf '# profile\tsource\tskill   — generated by `make capture`; hand edits are fine.\n'
  printf '# source "vendor" = copy in skills/vendor/, anything else = skills.sh / GitHub repo.\n'
  sort -t$'\t' -k1,1 -k3,3 "$rows"
} | out "$ROOT/skills/manifest.tsv"

# Plugins: marketplaces first, then user-scope plugins.
{
  printf '# kind\tname\tsource   — generated by `make capture`\n'
  [ -f "$CLAUDE_DIR/plugins/known_marketplaces.json" ] &&
    jq -r 'to_entries[] | select(.value.source.source=="github") | "marketplace\t\(.key)\t\(.value.source.repo)"' "$CLAUDE_DIR/plugins/known_marketplaces.json" | sort
  [ -f "$CLAUDE_DIR/plugins/installed_plugins.json" ] &&
    jq -r '.plugins | to_entries[] | select(any(.value[]; .scope=="user")) | "plugin\t\(.key)"' "$CLAUDE_DIR/plugins/installed_plugins.json" |
    grep -v $'\tpantheon@' | sort
} | out "$ROOT/plugins.tsv"

# skillOverrides travel with the skills they silence.
if [ -f "$CLAUDE_DIR/settings.json" ]; then
  frag="$ROOT/core/settings.json"; [ -f "$frag" ] || echo '{}' > "$frag"
  jq --slurpfile s "$CLAUDE_DIR/settings.json" '.skillOverrides = ($s[0].skillOverrides // {})' "$frag" | out "$frag.new"
  [ "$DRY_RUN" = 1 ] || mv "$frag.new" "$frag"
fi

stale=""
for d in "$ROOT"/skills/vendor/*/; do
  [ -d "$d" ] || continue; n="$(basename "$d")"
  awk -F'\t' -v n="$n" '$2=="vendor" && $3==n {f=1} END {exit !f}' "$rows" || stale="$stale $n"
done

echo "captured: $sourced from skills.sh sources, $vendored vendored"
[ -z "$skipped" ] || echo "skipped (off in skillOverrides):$skipped"
[ -z "$stale" ] || echo "vendor dirs no longer installed here (delete if unwanted):$stale"
